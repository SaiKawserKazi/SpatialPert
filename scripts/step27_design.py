"""A7: does the design-effect model reproduce the simulated (size-adjusted) power of the adopted test?

Also writes the empirical design table used by spatialpert.design.plan_screen_empirical.
Writes reports/step27_design.json and src/spatialpert/design_table.py.
"""

import json
from pathlib import Path

import numpy as np
from scipy.optimize import minimize_scalar

from spatialpert.design import DesignModel, plan_screen

ROOT = Path(__file__).resolve().parents[1]
adopt = json.loads((ROOT / "reports/step19_adoption.json").read_text())
icc = json.loads((ROOT / "reports/step23_icc.json").read_text())
real = json.loads((ROOT / "reports/step26_realism.json").read_text())

LS = [3, 5, 10, 20]
sim = {r["lesions"]: r["power_size_adjusted"] for r in adopt["per_test"]["loo_lesion"] if r.get("power_size_adjusted") is not None}
m_of = {L: 400 / L for L in LS}
icc_m = {int(k): v["per_gene_icc_median"] for k, v in icc.items()}


def rho_for(m: float) -> float:
    ks = np.array(sorted(icc_m))
    return float(np.interp(m, ks, [icc_m[k] for k in ks]))


def predicted(eff: float) -> np.ndarray:
    return np.array([float(plan_screen(L, m_of[L], 0.25, DesignModel(rho=rho_for(m_of[L]), sigma=1.0, efficiency=eff))) for L in LS])


obs = np.array([sim[L] for L in LS])
pred1 = predicted(1.0)
fit = minimize_scalar(lambda e: float(np.sum((predicted(e) - obs) ** 2)), bounds=(0.01, 5), method="bounded")
predf = predicted(float(fit.x))
corr = float(np.corrcoef(predf, obs)[0, 1]) if np.std(predf) > 0 else float("nan")
out = {
    "lesions": LS, "simulated_size_adjusted_power": obs.tolist(),
    "rho_used": {L: rho_for(m_of[L]) for L in LS},
    "formula_power_efficiency1": pred1.tolist(), "rmse_efficiency1": float(np.sqrt(np.mean((pred1 - obs) ** 2))),
    "fitted_efficiency": float(fit.x), "formula_power_fitted": predf.tolist(), "rmse_fitted": float(np.sqrt(np.mean((predf - obs) ** 2))),
    "corr_fitted_vs_sim": corr,
    "verdict": "",
}
out["verdict"] = ("design-effect model reproduces the curve" if out["rmse_fitted"] < 0.08
                  else "design-effect model does NOT reproduce the curve; plan_screen uses the simulated table")
(ROOT / "reports/step27_design.json").write_text(json.dumps(out, indent=2))
print(json.dumps(out, indent=2))

# empirical table: adopted test, log-scale lambda = 0.5 (400 cells) and count-level realism (delta 0.5/1.0, all genes)
real_pow = {}
for r in real["summary"]:
    pw = r["lesion"]["power"]
    real_pow[r["lesions"]] = {"d0.5": pw["d0.5_s1.0"]["size_adjusted"], "d1.0": pw["d1.0_s1.0"]["size_adjusted"]}
table = {"lesions": [1, *LS], "log_scale_lambda0.5": [0.0, *[sim[L] for L in LS]],
         "count_level_delta0.5": [0.0, 0.0, *[real_pow[L]["d0.5"] for L in (5, 10, 20)]],
         "count_level_delta1.0": [0.0, 0.0, *[real_pow[L]["d1.0"] for L in (5, 10, 20)]]}
src = ROOT / "src/spatialpert/design_table.py"
src.write_text(
    '"""Simulated power of the lesion-level test (400 cells), generated by scripts/step27_design.py.\n\n'
    'Do not edit by hand. Values are size-adjusted power at alpha = 0.05 from the tumour benchmark.\n"""\n\n'
    f"POWER_TABLE: dict[str, list[float]] = {json.dumps({k: [round(v, 4) for v in vs] for k, vs in table.items()}, indent=4)}\n"
)
print("wrote", src)
